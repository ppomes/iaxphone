package iax2

import "testing"

func TestMD5Response(t *testing.T) {
	// echo -n 1234secret | md5sum
	if got, want := MD5Response("1234", "secret"), "10b168cd4f742410888c3c110f7a7e71"; got != want {
		t.Errorf("MD5Response = %s, want %s", got, want)
	}
}
